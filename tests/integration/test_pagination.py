"""Paging through rows with NULL sort values in Postgres
returns every row exactly once, also past rows the resolver drops.

The SQL generated by `create_pagination` is tested in
tests/unit/test_pagination.py
"""

from dataclasses import dataclass
from typing import Any

import pytest

from ayon_server.lib.postgres import Postgres

# id, label, num, data
ROWS = [
    ("01", "b", 2, '{"fps": "25"}'),
    ("02", None, 1, '{"fps": "25"}'),
    ("03", "a", None, "{}"),
    ("04", None, None, '{"fps": null}'),
    ("05", "b", 1, '{"fps": "24"}'),
    ("06", "it's", None, '{"fps": "30"}'),
    ("07", None, 2, "{}"),
    ("08", "a", 2, '{"fps": "25"}'),
    ("09", "b", None, '{"fps": "24"}'),
    ("10", None, 1, "{}"),
    ("11", "c", 3, '{"fps": "30"}'),
]

SORTINGS = [
    ["t.label", "t.id"],
    ["t.num", "t.id"],
    ["(t.data->>'fps')", "t.id"],
    ["t.label", "t.num", "t.id"],
    ["t.num", "t.label", "t.id"],
    # "-" prefix: descending order
    ["-t.label", "t.id"],
    ["-t.num", "t.label", "t.id"],
    ["t.num", "-t.label", "t.id"],
    ["-(t.data->>'fps')", "-t.id"],
]


def _query(order_by: list[str], **kwargs: Any) -> str:
    # imports ayon_server.entities (see conftest)
    from ayon_server.graphql.resolvers.pagination import SortColumn, create_pagination

    columns = [
        SortColumn(c[1:], descending=True) if c.startswith("-") else c for c in order_by
    ]
    ordering, conditions, cursor = create_pagination(columns, **kwargs)
    values = ", ".join(
        "('{}', {}, {}, '{}'::jsonb)".format(
            id,
            "NULL" if label is None else "'{}'".format(label.replace("'", "''")),
            "NULL" if num is None else num,
            data,
        )
        for id, label, num, data in ROWS
    )
    return f"""
        WITH t(id, label, num, data) AS (VALUES {values})
        SELECT t.id, {cursor} FROM t
        {"WHERE " + conditions if conditions else ""}
        {ordering}
    """


async def _walk(order_by: list[str], page_size: int, backwards: bool) -> list[str]:
    from ayon_server.graphql.resolvers.pagination import encode_cursor

    result: list[str] = []
    cursor: str | None = None
    for _ in range(len(ROWS) + 1):
        if backwards:
            query = _query(order_by, last=page_size, before=cursor)
        else:
            query = _query(order_by, first=page_size, after=cursor)
        page = (await Postgres.fetch(query))[:page_size]
        if not page:
            return result
        result.extend(row["id"] for row in page)
        last_row = page[-1]
        cursor = encode_cursor([last_row[f"cursor_{i}"] for i in range(len(order_by))])
    raise AssertionError("Paging did not finish")


async def _all(order_by: list[str], backwards: bool) -> list[str]:
    kwargs = {"last": len(ROWS)} if backwards else {"first": len(ROWS)}
    return [row["id"] for row in await Postgres.fetch(_query(order_by, **kwargs))]


@pytest.mark.parametrize("order_by", SORTINGS, ids=lambda s: ",".join(s))
@pytest.mark.parametrize("backwards", [False, True], ids=["forward", "backward"])
@pytest.mark.parametrize("page_size", [1, 2, 3])
def test_paging_returns_every_row_once(run, order_by, backwards, page_size):
    expected = run(_all(order_by, backwards))
    assert sorted(expected) == sorted(row[0] for row in ROWS)
    assert run(_walk(order_by, page_size, backwards)) == expected


#
# Rows the resolver drops after the query (no access to them)
#


@dataclass
class Node:
    id: str

    @classmethod
    async def from_record(
        cls, project_name: str | None, record: dict[str, Any], context: dict[str, Any]
    ) -> "Node":
        from ayon_server.exceptions import ForbiddenException

        if record["id"] in context["forbidden"]:
            raise ForbiddenException()
        return cls(record["id"])


@dataclass
class Edge:
    node: Node
    cursor: str | None


@dataclass
class Connection:
    edges: list[Edge]
    page_info: Any


FORBIDDEN = [
    {"03"},
    {"02", "04", "06", "08", "10"},
    {"01", "02", "03", "04", "05", "06", "07"},
]


async def _walk_resolved(
    order_by: list[str],
    page_size: int,
    backwards: bool,
    skippable: bool,
    forbidden: set[str],
) -> list[str]:
    """Page like a client: follow hasNextPage (hasPreviousPage) and endCursor."""
    from ayon_server.graphql.resolvers.common import resolve

    result: list[str] = []
    cursor: str | None = None
    for _ in range(len(ROWS) + 1):
        if backwards:
            kwargs: dict[str, Any] = {"last": page_size, "before": cursor}
        else:
            kwargs = {"first": page_size, "after": cursor}
        connection = await resolve(
            Connection,
            Edge,
            Node,
            _query(order_by, skippable=skippable, **kwargs),
            first=kwargs.get("first"),
            last=kwargs.get("last"),
            context={"forbidden": forbidden},
            order_by=order_by,
        )
        result.extend(edge.node.id for edge in connection.edges)
        page_info = connection.page_info
        more = page_info.has_previous_page if backwards else page_info.has_next_page
        if not more:
            return result
        cursor = page_info.end_cursor
        assert cursor, "Another page without a cursor"
    raise AssertionError("Paging did not finish")


@pytest.mark.parametrize("order_by", SORTINGS, ids=lambda s: ",".join(s))
@pytest.mark.parametrize("backwards", [False, True], ids=["forward", "backward"])
@pytest.mark.parametrize("page_size", [1, 2, 3])
@pytest.mark.parametrize("skippable", [False, True], ids=["exact", "skippable"])
@pytest.mark.parametrize("forbidden", FORBIDDEN, ids=lambda f: ",".join(sorted(f)))
def test_paging_past_dropped_rows(
    run, order_by, backwards, page_size, skippable, forbidden
):
    """Pages with dropped rows don't end the paging: every other row is returned."""
    expected = [id for id in run(_all(order_by, backwards)) if id not in forbidden]
    walked = run(_walk_resolved(order_by, page_size, backwards, skippable, forbidden))
    assert walked == expected
