def current_info() -> FilmstripInfo:
    return {
        "version": filmstrip.FILMSTRIP_VERSION,
        "mime": filmstrip.FILMSTRIP_MIME,
        "frames": filmstrip.ayonconfig.filmstrip_frames,
        "columns": get_filmstrip_columns(filmstrip.ayonconfig.filmstrip_frames),
        "frameWidth": 480,
        "frameHeight": 270,
        "frameSize": filmstrip.ayonconfig.filmstrip_frame_size,
    }


def test_is_current():
    info = current_info()
    assert filmstrip._is_current(info)
    assert not filmstrip._is_current(None)
    assert not filmstrip._is_current({**info, "version": info["version"] - 1})
    assert not filmstrip._is_current({**info, "frames": info["frames"] + 1})
    assert not filmstrip._is_current({**info, "frameSize": info["frameSize"] + 1})


VIDEO_DATA: dict[str, Any] = {"mime": "video/mp4", "mediaInfo": {"videoTrackIndex": 0}}


def ensure(file_id: str, data: dict[str, Any]) -> FilmstripInfo:
    return asyncio.run(filmstrip._ensure_file_filmstrip("project", file_id, data))


def test_not_a_video():
    with pytest.raises(NotFoundException):
        ensure("file", {"mime": "image/png"})


def test_no_video_track():
    with pytest.raises(NotFoundException):
        ensure("file", {"mime": "video/mp4", "mediaInfo": {"videoTrackIndex": None}})


def test_current_filmstrip_is_not_recreated():
    info = current_info()
    assert ensure("file", {**VIDEO_DATA, "filmstrip": info}) == info


def test_build_queue_is_capped(monkeypatch: pytest.MonkeyPatch):
    async def no_failures(key: str) -> None:
        pass

    monkeypatch.setattr(filmstrip, "_check_failures", no_failures)
    info = current_info()

    async def run() -> None:
        pending = asyncio.get_running_loop().create_future()
        builds = {f"project:{i}": pending for i in range(filmstrip.MAX_PENDING_BUILDS)}
        monkeypatch.setattr(filmstrip, "_builds", builds)

        with pytest.raises(ServiceUnavailableException):
            await filmstrip._ensure_file_filmstrip("project", "new", VIDEO_DATA)
        assert len(builds) == filmstrip.MAX_PENDING_BUILDS

        # requests for filmstrips being created still wait for them
        waiter = asyncio.create_task(
            filmstrip._ensure_file_filmstrip("project", "0", VIDEO_DATA)
        )
        await asyncio.sleep(0)
        pending.set_result(info)
        assert await waiter == info

    asyncio.run(run())


