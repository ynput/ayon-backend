class FakeStorage:
    def __init__(self, payload: bytes | None):
        self.payload = payload

    async def get_filmstrip(self, file_id: str) -> bytes:
        if self.payload is None:
            raise FileNotFoundError(file_id)
        return self.payload


def get_payload(
    monkeypatch: pytest.MonkeyPatch,
    version: str | None,
    *,
    payload: bytes | None = b"avif",
    info: FilmstripInfo | None = None,
):
    async def get_storage(project_name: str) -> FakeStorage:
        return FakeStorage(payload)

    async def get_file_data(project_name: str, file_id: str) -> dict[str, Any]:
        return {"filmstrip": info} if info else {}

    monkeypatch.setattr(filmstrip.Storages, "project", get_storage)
    monkeypatch.setattr(filmstrip, "_get_file_data", get_file_data)
    return asyncio.run(get_filmstrip_payload_response("project", "file", version))


def test_payload_of_current_version_is_immutable(monkeypatch: pytest.MonkeyPatch):
    info = current_info()
    version = filmstrip._get_filmstrip_version(info)
    response = get_payload(monkeypatch, version, info=info)
    assert response.body == b"avif"
    assert response.media_type == filmstrip.FILMSTRIP_MIME
    assert "immutable" in response.headers["Cache-Control"]


def test_payload_without_version_is_not_cached(monkeypatch: pytest.MonkeyPatch):
    response = get_payload(monkeypatch, None, info=current_info())
    assert response.headers["Cache-Control"] == "private, no-cache"


def test_payload_of_other_version_is_not_found(monkeypatch: pytest.MonkeyPatch):
    info = current_info()
    with pytest.raises(NotFoundException):
        get_payload(monkeypatch, "0.20.480", info=info)
    # being re-created: the info is removed before the new image is stored
    with pytest.raises(NotFoundException):
        get_payload(monkeypatch, filmstrip._get_filmstrip_version(info), info=None)


def test_missing_payload_is_not_found(monkeypatch: pytest.MonkeyPatch):
    with pytest.raises(NotFoundException):
        get_payload(monkeypatch, None, payload=None, info=current_info())
