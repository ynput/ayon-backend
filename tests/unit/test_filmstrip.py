"""Filmstrip creation and serving (ayon_server.helpers.filmstrip).

Creation tests use clips generated by ffmpeg: the brightness of each frame
grows with its number, so the brightness of a filmstrip frame tells which
frame of the clip it was taken from.
"""

import asyncio
import io
import math
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest
from PIL import Image, ImageStat

from ayon_server.exceptions import NotFoundException, ServiceUnavailableException
from ayon_server.helpers import filmstrip
from ayon_server.helpers.filmstrip import (
    FilmstripError,
    FilmstripInfo,
    create_filmstrip,
    get_filmstrip_columns,
    get_filmstrip_payload_response,
)

FPS = 25
FRAMES = 20
FRAME_SIZE = 64

requires_ffmpeg = pytest.mark.skipif(
    not shutil.which("ffmpeg"), reason="ffmpeg is not available"
)


def make_clip(path: Path, frame_count: int) -> str:
    """Encode a grey clip whose frame N has brightness N * 255 / (frame_count - 1)

    Lossless RGB, so the brightness is not changed by a range conversion.
    """
    value = f"N*255/{max(frame_count - 1, 1)}"
    subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "lavfi",
            "-i",
            (
                f"color=c=black:s=96x54:r={FPS}:d={frame_count / FPS},"
                f"format=gbrp,geq=r='{value}':g='{value}':b='{value}'"
            ),
            "-frames:v",
            str(frame_count),
            "-c:v",
            "libx264rgb",
            "-qp",
            "0",
            str(path),
        ],
        check=True,
    )
    return str(path)


def frame_brightness(payload: bytes, info: FilmstripInfo) -> list[float]:
    """Mean brightness (0-255) of each filmstrip frame"""
    image = Image.open(io.BytesIO(payload)).convert("L")
    width, height = info["frameWidth"], info["frameHeight"]
    result = []
    for i in range(info["frames"]):
        x = (i % info["columns"]) * width
        y = (i // info["columns"]) * height
        frame = image.crop((x, y, x + width, y + height))
        result.append(ImageStat.Stat(frame).mean[0])
    return result


def create(path: str, frame_count: int) -> tuple[bytes, FilmstripInfo]:
    return asyncio.run(
        create_filmstrip(
            path,
            duration=frame_count / FPS,
            frames=FRAMES,
            frame_size=FRAME_SIZE,
            frame_rate=FPS,
        )
    )


def assert_layout(payload: bytes, info: FilmstripInfo) -> None:
    image = Image.open(io.BytesIO(payload))
    assert image.format == "AVIF"
    assert info["frames"] == FRAMES
    assert info["columns"] == get_filmstrip_columns(FRAMES)
    # fits the frame size box, keeps the aspect ratio
    assert (info["frameWidth"], info["frameHeight"]) == (64, 36)
    rows = math.ceil(FRAMES / info["columns"])
    assert image.size == (info["columns"] * 64, rows * 36)


def assert_segment_middles(brightness: list[float], frame_count: int) -> None:
    """Frame i is taken from the middle of the i-th of FRAMES segments"""
    for i, value in enumerate(brightness):
        expected = (i + 0.5) * frame_count / FRAMES * 255 / (frame_count - 1)
        assert abs(value - expected) < 12, (i, value, expected)


