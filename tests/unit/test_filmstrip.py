@requires_ffmpeg
def test_single_pass(tmp_path: Path):
    frame_count = 200
    payload, info = create(make_clip(tmp_path / "clip.mp4", frame_count), frame_count)
    assert_layout(payload, info)
    assert_segment_middles(frame_brightness(payload, info), frame_count)


@requires_ffmpeg
def test_seeking(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    # Seek even though the clip is short enough to be decoded at once
    monkeypatch.setattr(filmstrip, "SINGLE_PASS_MAX_FRAMES", 0)
    frame_count = 200
    payload, info = create(make_clip(tmp_path / "clip.mp4", frame_count), frame_count)
    assert_layout(payload, info)
    assert_segment_middles(frame_brightness(payload, info), frame_count)


@requires_ffmpeg
def test_clip_shorter_than_frames_is_spread_evenly(tmp_path: Path):
    frame_count = 5
    payload, info = create(make_clip(tmp_path / "clip.mp4", frame_count), frame_count)
    assert_layout(payload, info)
    brightness = frame_brightness(payload, info)
    # each clip frame is repeated in FRAMES / frame_count consecutive samples
    repeat = FRAMES // frame_count
    for i, value in enumerate(brightness):
        expected = (i // repeat) * 255 / (frame_count - 1)
        assert abs(value - expected) < 12, (i, value, expected)


def test_no_duration_fails():
    with pytest.raises(FilmstripError):
        asyncio.run(
            create_filmstrip(
                "missing.mp4", duration=0, frames=FRAMES, frame_size=FRAME_SIZE
            )
        )


@requires_ffmpeg
def test_undecodable_file_fails(tmp_path: Path):
    path = tmp_path / "broken.mp4"
    path.write_bytes(b"\x00" * 4096)
    with pytest.raises(FilmstripError):
        create(str(path), 100)


